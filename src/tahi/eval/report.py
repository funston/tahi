"""
Report rendering: reports are generated from artifacts, never authored by hand.

Two rules are enforced here rather than left to discipline:

1. Every arm reports every column in the schema. Dropping a metric requires
   removing it from METRIC_SCHEMA for all arms -- a reviewable diff -- instead
   of quietly omitting the column where the result was unfavourable.
2. Every rendered report carries its manifest. A number with no provenance
   cannot be published.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

# The schema IS the report. Adding a metric here makes it appear for every arm;
# removing one removes it for every arm. There is no per-arm column selection.
METRIC_SCHEMA: list[tuple[str, str, str]] = [
    # (json key, column header, format spec)
    ("n", "N", "d"),
    ("exact_match", "EM", ".3f"),
    ("token_f1", "F1", ".3f"),
    ("fact_coverage", "Fact Cov", ".3f"),
    ("groundedness", "Grounded", ".3f"),
    ("unsupported_rate", "Unsupported", ".3f"),
    ("supporting_fact_recall", "Doc Recall", ".3f"),
    ("abstention_accuracy", "Abstain Acc", ".3f"),
    ("ttft_ms", "TTFT (ms)", ".0f"),
    ("output_tokens", "Out Tok", ".0f"),
    ("cost_per_correct_usd", "$/Correct", ".4f"),
]


def _fmt(value: Any, spec: str) -> str:
    if value is None:
        return "n/a"
    try:
        return format(value, spec)
    except (TypeError, ValueError):
        return str(value)


def render_markdown(results_path: str | Path) -> str:
    """Render a results JSON into a Markdown report. Prose is not permitted here."""
    data = json.loads(Path(results_path).read_text(encoding="utf-8"))
    manifest = data.get("manifest", {})
    arms: list[dict[str, Any]] = data.get("arms", [])
    comparisons: list[dict[str, Any]] = data.get("comparisons", [])

    lines: list[str] = []
    lines.append(f"# {manifest.get('benchmark', 'Benchmark')} Results")
    lines.append("")
    lines.append(
        "> Generated by `tahi.eval.report`. Every number below is rendered from "
        f"`{Path(results_path).name}`. Do not hand-edit."
    )
    lines.append("")

    # Provenance first -- so a degraded run is visible before the numbers are.
    lines.append("## Run manifest")
    lines.append("")
    lines.append("| Field | Value |")
    lines.append("| --- | --- |")
    for key in (
        "dataset", "n_items", "model", "provider", "judge_model", "encoder",
        "encoder_is_fallback", "strict_mode", "git_sha", "git_dirty",
        "seed", "timestamp_utc", "wall_clock_s",
    ):
        if key in manifest:
            lines.append(f"| `{key}` | `{manifest[key]}` |")
    usage = manifest.get("llm_usage") or {}
    if usage:
        lines.append(
            f"| `llm_cost_usd` | `{usage.get('est_cost_usd', 'n/a')}` "
            f"({usage.get('total_calls', 0)} calls) |"
        )
    lines.append("")

    if manifest.get("encoder_is_fallback") or not manifest.get("strict_mode", True):
        lines.append(
            "> [!CAUTION]\n"
            "> This run was **degraded** (fallback encoder or non-strict mode). "
            "The numbers below are not a valid measurement."
        )
        lines.append("")

    # Results: every arm, every column.
    lines.append("## Results")
    lines.append("")
    headers = [h for _, h, _ in METRIC_SCHEMA]
    lines.append("| Arm | " + " | ".join(headers) + " |")
    lines.append("| --- | " + " | ".join("---:" for _ in headers) + " |")
    for arm in arms:
        cells = [_fmt(arm.get(k), spec) for k, _, spec in METRIC_SCHEMA]
        lines.append(f"| **{arm.get('name', '?')}** | " + " | ".join(cells) + " |")
    lines.append("")

    # Significance: a delta without a CI is not reported as a result.
    if comparisons:
        lines.append("## Paired comparisons")
        lines.append("")
        lines.append("| Comparison | Delta | 95% CI | Significant | p (McNemar) |")
        lines.append("| --- | ---: | :---: | :---: | ---: |")
        for c in comparisons:
            ci = f"[{c.get('ci_low', 0):+.4f}, {c.get('ci_high', 0):+.4f}]"
            sig = "yes" if c.get("ci_excludes_zero") else "**no**"
            p = c.get("p_value")
            lines.append(
                f"| {c.get('arm_b')} vs {c.get('arm_a')} | {c.get('delta', 0):+.4f} | "
                f"{ci} | {sig} | {_fmt(p, '.4f')} |"
            )
        lines.append("")
        for c in comparisons:
            lines.append(f"- {c.get('verdict', '')}")
        lines.append("")

    if manifest.get("notes"):
        lines.append("## Notes")
        lines.append("")
        lines.append(manifest["notes"])
        lines.append("")

    return "\n".join(lines)


def write_report(results_path: str | Path, out_path: str | Path | None = None) -> Path:
    results_path = Path(results_path)
    out = Path(out_path) if out_path else results_path.with_suffix(".md")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_markdown(results_path), encoding="utf-8")
    return out


if __name__ == "__main__":
    import argparse

    ap = argparse.ArgumentParser(description="Render a benchmark results JSON to Markdown.")
    ap.add_argument("results", help="Path to results JSON")
    ap.add_argument("-o", "--output", default=None, help="Output .md path")
    args = ap.parse_args()
    print(f"Wrote {write_report(args.results, args.output)}")
